def apply_variant(
    base_question: str,
    variant_type: str,
    kernel_id: int,
    test_type: str
) -> str:
    """Apply a variant template to a base question."""
    
    if variant_type == "base":
        return base_question
    
    template = VARIANT_TEMPLATES.get(variant_type)
    if not template:
        return base_question
    
    prefix = template.prefix
    suffix = template.suffix
    
    # For 'friend' variant, insert quotes and examples
    if variant_type == "friend":
        prefix = prefix.format(
            canonical_quote=get_canonical_quote(kernel_id),
            concrete_example=get_concrete_example(kernel_id, test_type)
        )
    
    return prefix + base_question + suffix


