class ExperimentPhase(str, Enum):
    """Three phases of the experiment."""
    SAMPLING = "phase_1_sampling"
    ADVERSARIAL = "phase_2_adversarial"
    DEEP_DIVE = "phase_3_deep_dive"


@dataclass
class PhaseConfig:
    """Configuration for each phase."""
    phase: ExperimentPhase
    
    # Kernel selection
    kernel_ids: List[int]
    
    # Model configuration
    models: List[str]
    quantizations: List[str]
    
    # Language/formulation
    languages: List[str]
    formulations: List[str]
    
    # Question variants
    variants: List[str]  # base, angel, demon, friend
    
    # Evaluation
    evaluator_models: List[str]
    arbiter_threshold: float  # When to escalate to Opus
    
    # Estimated requests
    @property
    def estimated_requests(self) -> int:
        base = (
            len(self.kernel_ids) * 
            len(self.models) * 
            len(self.languages) * 
            len(self.formulations) *
            len(self.variants)
        )
        evaluation = base * len(self.evaluator_models)
        return base + evaluation


