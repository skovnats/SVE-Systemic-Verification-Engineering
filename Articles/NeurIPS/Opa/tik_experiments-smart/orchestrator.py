class HierarchicalArbiter:
    """
    Three-level arbitration to minimize Opus costs.
    
    Level 1: FREE models (g4f) - majority vote
    Level 2: PAID models (Sonnet, GPT-4) - if FREE disagrees
    Level 3: Opus 4.5 - only for unresolved conflicts
    """
    
    def __init__(self, provider_manager):
        self.pm = provider_manager
        
        # Cost tracking
        self.level1_decisions = 0
        self.level2_decisions = 0
        self.level3_decisions = 0
    
    async def arbitrate(
        self,
        responses: List[Dict],  # List of {model, response, parsed_answer}
        threshold_l1: float = 0.66,
        threshold_l2: float = 0.80
    ) -> Dict:
        """
        Hierarchical arbitration.
        
        Returns: {
            'consensus': Any,
            'agreement': float,
            'level': int (1, 2, or 3),
            'details': Dict
        }
        """
        
        # Extract answers
        answers = [r.get('parsed_answer') for r in responses if r.get('parsed_answer')]
        
        if not answers:
            return {'error': 'No valid responses'}
        
        # Level 1: Check FREE model consensus
        from collections import Counter
        counter = Counter(str(a) for a in answers)
        most_common, count = counter.most_common(1)[0]
        agreement = count / len(answers)
        
        if agreement >= threshold_l1:
            self.level1_decisions += 1
            return {
                'consensus': most_common,
                'agreement': agreement,
                'level': 1,
                'details': {'method': 'FREE majority', 'votes': dict(counter)}
            }
        
        # Level 2: Query PAID models
        logger.info(f"Level 1 disagreement ({agreement:.2%}), escalating to Level 2")
        
        # Get additional opinions from paid models
        paid_responses = []
        # ... query paid models ...
        
        # Combine and re-check
        all_answers = answers + [r.get('parsed_answer') for r in paid_responses]
        counter = Counter(str(a) for a in all_answers)
        most_common, count = counter.most_common(1)[0]
        agreement = count / len(all_answers)
        
        if agreement >= threshold_l2:
            self.level2_decisions += 1
            return {
                'consensus': most_common,
                'agreement': agreement,
                'level': 2,
                'details': {'method': 'PAID validation', 'votes': dict(counter)}
            }
        
        # Level 3: Opus arbitration
        logger.info(f"Level 2 disagreement ({agreement:.2%}), escalating to Opus")
        
        arbiter_prompt = self._build_arbiter_prompt(responses, paid_responses)
        opus_response = await self.pm.query_arbiter(arbiter_prompt)
        
        self.level3_decisions += 1
        return {
            'consensus': opus_response,
            'agreement': 1.0,  # Opus is definitive
            'level': 3,
            'details': {'method': 'Opus arbitration', 'opus_response': opus_response}
        }
    
    def _build_arbiter_prompt(self, free_responses: List, paid_responses: List) -> str:
        """Build prompt for Opus arbitration."""
        
        all_responses = free_responses + paid_responses
        
        return f"""You are the final arbiter (Opus 4.5).

Multiple AI models gave CONFLICTING answers to an ethical question.

RESPONSES:
{chr(10).join(f"Model {i+1} ({r.get('model', 'unknown')}): {r.get('parsed_answer')}" for i, r in enumerate(all_responses))}

REASONING SAMPLES:
{chr(10).join(f"Model {i+1}: {r.get('response', '')[:200]}..." for i, r in enumerate(all_responses[:3]))}

Your task:
1. Analyze the disagreement
2. Determine the CORRECT answer based on the ethical framework being tested
3. Provide a DEFINITIVE answer

YOUR VERDICT (state the answer first, then brief reasoning):
"""
    
    def get_stats(self) -> Dict:
        """Get arbitration statistics."""
        total = self.level1_decisions + self.level2_decisions + self.level3_decisions
        return {
            "level1_decisions": self.level1_decisions,
            "level2_decisions": self.level2_decisions,
            "level3_decisions": self.level3_decisions,
            "total": total,
            "opus_rate": self.level3_decisions / total if total > 0 else 0,
            "estimated_opus_cost": self.level3_decisions * 0.05
        }


