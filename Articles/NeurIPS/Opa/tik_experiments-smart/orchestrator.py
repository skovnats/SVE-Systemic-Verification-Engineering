class ExperimentCache:
    """
    Cache for experiment results.
    
    Key = hash(kernel_id + model + quantization + language + formulation + variant)
    
    Saves MASSIVE costs by not re-running identical queries.
    """
    
    def __init__(self, redis_client=None, postgres_conn=None):
        self.redis = redis_client
        self.postgres = postgres_conn
        self.local_cache: Dict[str, Any] = {}
        self.hits = 0
        self.misses = 0
    
    def _make_key(
        self,
        kernel_id: int,
        model: str,
        quantization: str,
        language: str,
        formulation: str,
        variant: str,
        test_type: str
    ) -> str:
        """Create cache key."""
        raw = f"{kernel_id}:{model}:{quantization}:{language}:{formulation}:{variant}:{test_type}"
        return hashlib.sha256(raw.encode()).hexdigest()[:32]
    
    async def get(
        self,
        kernel_id: int,
        model: str,
        quantization: str,
        language: str,
        formulation: str,
        variant: str,
        test_type: str
    ) -> Optional[Dict]:
        """Get cached result if exists."""
        
        key = self._make_key(
            kernel_id, model, quantization, language, formulation, variant, test_type
        )
        
        # Check local cache first
        if key in self.local_cache:
            self.hits += 1
            return self.local_cache[key]
        
        # Check Redis
        if self.redis:
            try:
                data = await self.redis.get(f"tik:cache:{key}")
                if data:
                    self.hits += 1
                    result = json.loads(data)
                    self.local_cache[key] = result
                    return result
            except Exception as e:
                logger.warning(f"Redis cache error: {e}")
        
        self.misses += 1
        return None
    
    async def set(
        self,
        kernel_id: int,
        model: str,
        quantization: str,
        language: str,
        formulation: str,
        variant: str,
        test_type: str,
        result: Dict
    ):
        """Cache a result."""
        
        key = self._make_key(
            kernel_id, model, quantization, language, formulation, variant, test_type
        )
        
        # Local cache
        self.local_cache[key] = result
        
        # Redis (with 7-day expiry)
        if self.redis:
            try:
                await self.redis.setex(
                    f"tik:cache:{key}",
                    7 * 24 * 3600,  # 7 days
                    json.dumps(result, default=str)
                )
            except Exception as e:
                logger.warning(f"Redis cache set error: {e}")
    
    def get_stats(self) -> Dict:
        """Get cache statistics."""
        total = self.hits + self.misses
        return {
            "hits": self.hits,
            "misses": self.misses,
            "hit_rate": self.hits / total if total > 0 else 0,
            "local_size": len(self.local_cache),
            "estimated_savings": self.hits * 0.01  # ~$0.01 per cached request
        }


